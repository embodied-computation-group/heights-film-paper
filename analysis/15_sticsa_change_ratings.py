"""Step 15 (EXPLORATORY, post hoc): STICSA somatic change against the ratings in each of the four segments.

Not registered. The registered tests relate STICSA change to the whole-film mean ratings (H5a, H5b); this analysis
asks how that association develops over the film. Because it is exploratory, it uses everyone who passes the
registered exclusions in BOTH samples (confirmatory and exploratory, pooled). For each rating (arousal, valence) and
each registered segment (baseline, rise, plateau, return): Spearman rho between STICSA change (post - pre) and the
participant's segment mean, with a bootstrap 95% CI (5000 resamples of participants). p values are uncorrected; a
Holm adjustment over the eight correlations is added to the table as a check.

Run:  uv run python analysis/15_sticsa_change_ratings.py

Writes results/pooled/exploratory_sticsa_by_segment.csv, results/pooled/figures/fig9_sticsa_by_segment,
Figure 3 of the manuscript (manuscript/figures/figure3) and manuscript/generated/sticsa_segment_numbers.tex
(\\val{xseg:...} keys).
"""
import sys
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))  # so `analysis` can be imported
from analysis import hypotheses, plot_style, run_record, stats_tools, study_data  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "results" / "pooled"
GENERATED = ROOT / "manuscript" / "generated"
SEED = 20261004
RATINGS = {"arousal": ("Arousal (0–100)", plot_style.AROUSAL), "valence": ("Valence (0–100)", plot_style.VALENCE)}


def correlations_by_segment(measures):
    """One row per rating and segment: Spearman rho of STICSA change with the segment mean."""
    rows = []
    for rating in RATINGS:
        for segment in study_data.SEGMENTS:
            result = stats_tools.spearman_with_ci(measures["sticsa_change"], measures[f"{rating}_{segment}"],
                                                  seed=SEED)
            rows.append({"rating": rating, "segment": segment, **result})
    table = pd.DataFrame(rows)
    table["p_holm_8"] = stats_tools.holm(table["p"].to_numpy())
    return table


def figure(measures, table, note, path):
    """Top row arousal, bottom row valence; one column per segment, shaded as in the other figures."""
    jitter = np.random.default_rng(0)  # only moves points sideways so they do not hide each other
    segments = list(study_data.SEGMENTS)
    fig, axes = plt.subplots(2, len(segments), figsize=(9.6, 5.0), sharex=True, sharey=True)
    for row, (rating, (label, colour)) in enumerate(RATINGS.items()):
        for col, segment in enumerate(segments):
            ax = axes[row, col]
            column = f"{rating}_{segment}"
            pair = measures[["sticsa_change", column]].dropna()
            x = pair["sticsa_change"] + jitter.uniform(-0.25, 0.25, len(pair))
            ax.scatter(x, pair[column], s=10, color=colour, alpha=0.5, edgecolor="white", linewidth=0.4)
            # Trend line: least-squares fit with 95% band (a visual guide; the statistic is Spearman's rho).
            grid = np.linspace(pair["sticsa_change"].min(), pair["sticsa_change"].max(), 100)
            fit, low, high = stats_tools.linear_fit_band(pair["sticsa_change"], pair[column], grid)
            ax.fill_between(grid, low, high, color=plot_style.TEXT, alpha=0.2, lw=0, zorder=2)
            ax.plot(grid, fit, color=plot_style.TEXT, lw=1.3, zorder=3)
            ax.set_facecolor(plot_style.SEGMENT_SHADES[segment])
            result = table.set_index(["rating", "segment"]).loc[(rating, segment)]
            start, end = study_data.SEGMENTS[segment]
            heading = f"{segment.capitalize()} ({start}–{end} s)\n" if row == 0 else ""
            ax.set_title(f"{heading}ρ = {result['rho']:.2f}, 95% CI [{result['ci_low']:.2f}, {result['ci_high']:.2f}]",
                         loc="left", fontsize=7.5)
            ax.set_ylim(-3, 103)
            if col == 0:
                ax.set_ylabel(f"Segment mean {label[0].lower()}{label[1:]}", fontsize=8)
            if row == 1:
                ax.set_xlabel("STICSA change (points)", fontsize=8)
    fig.tight_layout()
    if note:
        fig.text(0.995, 0.005, note, ha="right", va="bottom", fontsize=7, color=plot_style.TEXT_SOFT)
    plot_style.save(fig, path)


def tex_numbers(table, n):
    """\\val{} definitions for the manuscript: one report string per rating and segment, and n."""
    def number(value):
        return f"{value:.2f}".replace("0.", ".", 1).replace("-", "$-$")

    lines = ["% Generated by analysis/15_sticsa_change_ratings.py - EXPLORATORY (both samples). Do not edit by hand.",
             f"\\expandafter\\def\\csname val:xseg:n\\endcsname{{{n}}}"]
    for _, row in table.iterrows():
        p = "$p$ < .001" if row["p"] < 0.001 else f"$p$ = {row['p']:.3f}".replace("0.", ".", 1)
        report = f"$\\rho$ = {number(row['rho'])}, 95\\% CI [{number(row['ci_low'])}, {number(row['ci_high'])}], {p}"
        key = f"xseg:{row['rating']}:{row['segment']}"
        lines.append(f"\\expandafter\\def\\csname val:{key}\\endcsname{{{report}}}")
    return "\n".join(lines) + "\n"


def main():
    record = run_record.make_record("15_sticsa_change_ratings.py", "pooled (exploratory + confirmatory)", seed=SEED,
                                    inputs=sorted(study_data.DATA.glob("*.csv")))
    plot_style.use()

    participants, valence, arousal = study_data.load()
    measures = hypotheses.participant_measures(participants, valence, arousal)
    usable = participants[study_data.is_usable(participants)]  # registered exclusions, both samples
    group = measures.loc[usable.index]
    print("n by sample:", usable["sample"].value_counts().to_dict())

    table = correlations_by_segment(group)
    OUT.mkdir(parents=True, exist_ok=True)
    table.to_csv(OUT / "exploratory_sticsa_by_segment.csv", index=False)
    print(table.to_string(index=False))

    figure(group, table, "Both samples pooled (exploratory analysis)", OUT / "figures" / "fig9_sticsa_by_segment")
    plt.rcParams["savefig.dpi"] = 600  # journal production
    figure(group, table, None, ROOT / "manuscript" / "figures" / "figure3")
    (GENERATED / "sticsa_segment_numbers.tex").write_text(tex_numbers(table, len(group)), encoding="utf-8")
    print("wrote", GENERATED / "sticsa_segment_numbers.tex")
    run_record.save_record(record, OUT)


if __name__ == "__main__":
    main()
