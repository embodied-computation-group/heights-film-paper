"""Step 13: how the rating platform performed (DESCRIPTIVE, not preregistered), for the Methodology article.

Summarises the quality columns already exported for every completed session: retention under the registered
exclusion rules, film coverage, buffering and interruptions, rating behaviour, input device, attention checks and
self-reported attention. Retention is reported among COMPLETED sessions (not as a study completion rate).

Page reloads and resumed sessions are not in data/processed/ (they are only in the raw logs of the tooling
repository), so they are not reported here.

Run:  uv run python analysis/13_platform_quality.py
Writes manuscript/generated/platform_numbers.tex (\\val{pq:...} keys) and a run record in results/confirmatory/.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))  # so `analysis` can be imported
from analysis import platform_quality as pq  # noqa: E402
from analysis import run_record, study_data  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "manuscript" / "generated"
RECORDS = ROOT / "results" / "confirmatory"


def tex_line(key, value):
    """One \\val{} definition in the same form as generated/numbers.tex."""
    return f"\\expandafter\\def\\csname val:{key}\\endcsname{{{value}}}"


def numbers_for(sessions, prefix):
    """All platform numbers for one sample, as {key: formatted text}."""
    kept = sessions[pq.is_usable(sessions)]
    retention = pq.retention(sessions)
    delivery = pq.delivery(sessions)
    behaviour = pq.rating_behaviour(kept)
    devices = pq.counts(sessions, "input_device")
    attention = pq.attention_checks(sessions)
    attentive = pq.counts(sessions, "full_attention")
    values = {
        "completed": retention["completed"],
        "usable": retention["usable"],
        "pct_usable": f"{retention['percent_usable']:.1f}",
        "coverage_median": f"{100 * delivery['coverage_median']:.0f}",
        "coverage_min": f"{100 * delivery['coverage_min']:.1f}",
        "n_any_buffering": delivery["n_any_buffering"],
        "buffering_max": f"{delivery['buffering_max_s']:.0f}",
        "n_any_interruption": delivery["n_any_interruption"],
        "interrupted_max": f"{delivery['interrupted_max_s']:.0f}",
        "bouts_median": f"{behaviour['bouts_median']:.1f}",
        "bouts_q1": f"{behaviour['bouts_q1']:.1f}",
        "bouts_q3": f"{behaviour['bouts_q3']:.1f}",
        "gap_median": f"{behaviour['gap_median_s']:.0f}",
        "n_sparse": behaviour["n_sparse"],
        "n_mouse": devices.get("Mouse", 0),
        "n_trackpad": devices.get("Trackpad / touchpad", 0),
        "n_other_device": devices.get("Other", 0),
        "att_none": attention["failed_none"],
        "att_one": attention["failed_one"],
        "att_both": attention["failed_both"],
        "attentive_yes": attentive.get("Yes", 0),
        "attentive_mostly": attentive.get("Mostly", 0),
        "attentive_no": attentive.get("No", 0),
    }
    return {f"pq:{prefix}:{key}": value for key, value in values.items()}


def main():
    record = run_record.make_record("13_platform_quality.py", "confirmatory and exploratory", seed=None,
                                    inputs=sorted(study_data.DATA.glob("*.csv")))
    participants, _, _ = study_data.load()
    numbers = {}
    for sample in ("confirmatory", "exploratory"):
        numbers.update(numbers_for(participants[participants["sample"] == sample], sample[:4]))

    OUT.mkdir(parents=True, exist_ok=True)
    lines = ["% Generated by analysis/13_platform_quality.py - descriptive platform numbers. Do not edit by hand."]
    lines += [tex_line(key, value) for key, value in numbers.items()]
    (OUT / "platform_numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    run_record.save_record(record, RECORDS)
    for key, value in numbers.items():
        print(f"{key:32s} {value}")


if __name__ == "__main__":
    main()
